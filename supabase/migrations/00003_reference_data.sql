create or replace function pg_temp.make_stages(total_days integer)
returns jsonb language sql immutable as $$
  select jsonb_build_array(
    jsonb_build_object('stage','land_preparation','days', greatest(3, round(total_days*0.08)::int)),
    jsonb_build_object('stage','sowing','days', 1),
    jsonb_build_object('stage','germination','days', greatest(4, round(total_days*0.07)::int)),
    jsonb_build_object('stage','vegetative','days', greatest(10, round(total_days*0.33)::int)),
    jsonb_build_object('stage','flowering','days', greatest(7, round(total_days*0.18)::int)),
    jsonb_build_object('stage','fruiting','days', greatest(7, round(total_days*0.22)::int)),
    jsonb_build_object('stage','harvesting','days', greatest(3, round(total_days*0.11)::int))
  );
$$;

